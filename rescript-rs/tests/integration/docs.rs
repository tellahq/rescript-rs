/// Supports new lines.
///
/// Testing
enum E {}

#[derive(TS)]
#[cfg_attr(feature = "serde-compat", derive(Serialize))]
#[cfg_attr(feature = "serde-compat", serde(tag = "type", content = "value"))]
#[cfg_attr(
    not(feature = "serde-compat"),
    rescript(tag = "type", content = "value")
)]
#[rescript(export_to = "docs/")]
/// Doc comment.
/// Supports new lines.
///
/// Testing
enum F {
    /// Doc of variant
    ///
    /// Testing
    VarA,
    /// Doc of variant
    ///
    /// Testing
    VarB(),
    /// Doc of variant
    ///
    /// Testing
    VarC {
        /// Doc of field of variant
        ///
        /// Testing
        variant_field: i32,
    },
}

#[derive(TS)]
#[rescript(export_to = "docs/")]
struct G {
    /// Docs
    some_other_field: i32,

    /// Some documentation that should probably NOT be exported
    #[rescript(flatten)]
    f: F,
}

#[derive(TS)]
#[rescript(export_to = "docs/")]
/**
 * Block doc comment
 *
 * works
 */
struct H {
    foo: i32,
}

#[derive(TS)]
#[rescript(export_to = "docs/")]
#[doc = concat!("line ", line!())]
struct I {
    #[doc = concat!("column ", column!())]
    a: i32,

    #[doc = concat!("path ", module_path!())]
    b: i32,
}

#[test]
fn export_a() {
    let cfg = Config::from_env();
    A::export(&cfg).unwrap();

    let expected_content = concat!(
        "// This file was generated by [rescript-rs](https://github.com/nicholasgasior/rescript-rs). Do not edit this file manually.\n@@warning(\"-30\")\n\n",
        "/**\n",
        " * Doc comment.\n",
        " * Supports new lines.\n",
        " *\n",
        " * Testing\n",
        " */\n",
        "type a = {\n",
        "  /**\n",
        " * Doc of field\n",
        " *\n",
        " * Testing\n",
        " */\n",
        "  name: string,\n",
        "}\n",
    );

    let actual_content = super::read_file::<A>(&cfg);
    assert_eq!(actual_content, expected_content);
}


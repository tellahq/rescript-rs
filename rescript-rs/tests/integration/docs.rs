#![allow(dead_code)]

use std::{concat, fs};

use rescript_rs::{Config, TS};
#[cfg(feature = "serde-compat")]
use serde::Serialize;

/// Doc comment.
/// Supports new lines.
///
/// Testing
#[derive(TS)]
#[rescript(export_to = "docs/")]
struct A {
    /// Doc of field
    ///
    /// Testing
    name: String,
}

#[derive(TS)]
#[rescript(export_to = "docs/")]
/// Doc comment.
/// Supports new lines.
